function params(string $p): string
{
    return str_starts_with($p, 'N ') ? 'Tag|string ' . substr($p, 2) : $p;
}

function method(string $doc, string $name, string $params, string $result, string $body): string
{
    return "    /** $doc */\n    public function $name(" . params($params) . "): $result\n    {\n$body    }\n\n";
}

function block(string $scope): string
{
    $b = "    // Generated by tools/gen.php; do not edit by hand.\n\n";
    foreach (FINDS as [$name, $params, $query, $guard, $doc]) {
        $body = $guard === '' ? '' : "        if ($guard) {\n            return null;\n        }\n";
        $body .= "        return \$this->find($query);\n";
        $b .= method("Returns $doc $scope, or null.", $name, $params, '?HtmlNode', $body);
    }
    foreach (FIND_ALLS as [$name, $params, $query, $doc]) {
        $b .= "    /**\n     * Returns $doc $scope.\n     *\n     * @return list<HtmlNode>\n     */\n";
        $b .= "    public function $name(" . params($params) . "): array\n    {\n        return \$this->findAll($query);\n    }\n\n";
    }
    return $b;
}

function nodeOnly(): string
{
    $b = '';
    foreach (ISS as [$name, $params, $query, $doc]) {
        $b .= method("Whether $doc.", $name, $params, 'bool', "        return \$this->is($query);\n");
    }
    foreach (NAVS as [$name, $params, $call, $result, $doc]) {
        $b .= method("Returns $doc.", $name, $params, $result, "        return $call;\n");
    }
    foreach (ATTRIBUTES as [$name, $constant, $attribute]) {
        $b .= method("The decoded value of the $attribute attribute; \"\" when it is missing.", $name, '', 'string',
            "        return \$this->attr(Attr::$constant);\n");
    }
    return $b;
}

function shortcuts(): void
{
    replaceBlock('HtmlDocument.php', 'document', block('in the document'));
    replaceBlock('HtmlNode.php', 'node', block('inside the tag') . nodeOnly());
}

function replaceBlock(string $file, string $marker, string $content): void
{
    $path = OUT . $file;
    $text = read($path);
    $open = "    // <shortcuts $marker>\n";
    $close = "    // </shortcuts $marker>";
    $a = strpos($text, $open);
    $z = strpos($text, $close);
    if ($a === false || $z === false || $z < $a) {
        throw new RuntimeException("no shortcut markers in $file");
    }
    $body = str_ends_with($content, "\n\n") ? substr($content, 0, -1) : $content;
    file_put_contents($path, substr($text, 0, $a + strlen($open)) . $body . substr($text, $z));
}

