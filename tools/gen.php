<?php

// Builds Tag.php, TagNames.php, Attr.php and Entities.php from the C# sources of z3l.FastHtmlParser, so that the PHP
// port uses exactly the same tag list, attribute names and HTML5 entity table, and writes the one-call shortcuts
// (findByNameClass, isNameClass, parentByName, ...) into HtmlDocument.php and HtmlNode.php between the
// "// <shortcuts ...>" markers.
//
//   php tools/gen.php ../z3l.FastHtmlParser/src/z3l.FastHtmlParser

declare(strict_types=1);

const OUT = __DIR__ . '/../src/';
const NS = "namespace Z3l\\FastHtmlParser;\n\n";

function main(array $argv): void
{
    if (count($argv) !== 2) {
        fwrite(STDERR, "usage: php tools/gen.php <path to src/z3l.FastHtmlParser>\n");
        exit(2);
    }
    $src = rtrim($argv[1], '/\\') . '/';
    $tags = tags($src);
    $attributes = attributes($src);
    $entities = entities($src);
    shortcuts();
    echo "$tags tags, $attributes attributes, $entities entities, shortcuts written\n";
}

function read(string $path): string
{
    $text = file_get_contents($path);
    if ($text === false) {
        throw new RuntimeException("cannot read $path");
    }
    return str_replace("\r\n", "\n", $text);
}

function write(string $name, string $text): void
{
    file_put_contents(OUT . $name, $text);
}

function header_for(string $from): string
{
    return "<?php\n\n// Code generated by tools/gen.php from $from; DO NOT EDIT.\n\ndeclare(strict_types=1);\n\n" . NS;
}

/** The member names of a C# enum without explicit values, in order. */
function enumMembers(string $path, string $name): array
{
    $text = read($path);
    $body = substr($text, strpos($text, "public enum $name"));
    $body = substr($body, strpos($body, '{') + 1, strrpos($body, '}') - strpos($body, '{') - 1);
    $members = [];
    foreach (explode("\n", $body) as $line) {
        $comment = strpos($line, '//');
        if ($comment !== false) {
            $line = substr($line, 0, $comment);
        }
        $line = rtrim(trim($line), ',');
        $line = trim($line);
        if ($line !== '') {
            $members[] = $line;
        }
    }
    return $members;
}

/** PascalCase to UPPER_SNAKE: DataSrc → DATA_SRC, XmlDeclaration → XML_DECLARATION, H1 → H1. */
function constant_name(string $pascal): string
{
    $b = '';
    for ($i = 0; $i < strlen($pascal); $i++) {
        $c = $pascal[$i];
        if ($i > 0 && ctype_upper($c)) {
            $prev = $pascal[$i - 1];
            if (ctype_lower($prev) || ctype_digit($prev)) {
                $b .= '_';
            }
        }
        $b .= strtoupper($c);
    }
    return $b;
}

function php_string(string $s): string
{
    $b = '"';
    $n = strlen($s);
    for ($i = 0; $i < $n;) {
        $c = ord($s[$i]);
        if ($c < 0x80) {
            $ch = $s[$i];
            $b .= match (true) {
                $ch === '"' => '\\"',
                $ch === '\\' => '\\\\',
                $ch === '$' => '\\$',
                $ch === "\n" => '\\n',
                $ch === "\t" => '\\t',
                $c < 0x20 || $c === 0x7f => sprintf('\\x%02x', $c),
                default => $ch,
            };
            $i++;
            continue;
        }
        $len = $c >= 0xf0 ? 4 : ($c >= 0xe0 ? 3 : 2);
        $b .= sprintf('\\u{%x}', utf8_code_point(substr($s, $i, $len)));
        $i += $len;
    }
    return $b . '"';
}

function utf8_code_point(string $ch): int
{
    $c = ord($ch[0]);
    if ($c < 0x80) {
        return $c;
    }
    if ($c < 0xe0) {
        return (($c & 0x1f) << 6) | (ord($ch[1]) & 0x3f);
    }
    if ($c < 0xf0) {
        return (($c & 0x0f) << 12) | ((ord($ch[1]) & 0x3f) << 6) | (ord($ch[2]) & 0x3f);
    }
    return (($c & 0x07) << 18) | ((ord($ch[1]) & 0x3f) << 12) | ((ord($ch[2]) & 0x3f) << 6) | (ord($ch[3]) & 0x3f);
}

function utf8(int $cp): string
{
    if ($cp < 0x80) {
        return chr($cp);
    }
    if ($cp < 0x800) {
        return chr(0xc0 | ($cp >> 6)) . chr(0x80 | ($cp & 0x3f));
    }
    if ($cp < 0x10000) {
        return chr(0xe0 | ($cp >> 12)) . chr(0x80 | (($cp >> 6) & 0x3f)) . chr(0x80 | ($cp & 0x3f));
    }
    return chr(0xf0 | ($cp >> 18)) . chr(0x80 | (($cp >> 12) & 0x3f)) . chr(0x80 | (($cp >> 6) & 0x3f)) . chr(0x80 | ($cp & 0x3f));
}

// ----- tags -----

function tags(string $src): int
{
    $special = ['Comment' => '!--', 'Doctype' => '!doctype', 'XmlDeclaration' => '?xml'];
    $members = enumMembers($src . 'HtmlTag.cs', 'HtmlTag');
    $b = header_for('HtmlTag.cs');
    $b .= "/**\n * Known tag names: HTML (incl. obsolete), SVG, MathML and common XML (RSS, Atom, sitemap). The value is the\n";
    $b .= " * lower-case tag name (\"div\", \"!--\" for comments, \"!doctype\", \"?xml\"). Any other name works as a plain string in\n";
    $b .= " * the methods that take a tag name.\n */\n";
    $b .= "enum Tag: string\n{\n";
    $names = [];
    foreach ($members as $m) {
        $name = $special[$m] ?? strtolower($m);
        if (isset($names[$name])) {
            throw new RuntimeException("duplicate tag $name");
        }
        $names[$name] = count($names);
        $b .= "    case $m = '$name';\n";
    }
    $b .= "}\n";
    write('Tag.php', $b);

    $t = header_for('HtmlTag.cs');
    $t .= "/**\n * @internal The tag names by ordinal (the order of the C# enum) and the ordinals by name.\n */\n";
    $t .= "final class TagNames\n{\n";
    $t .= "    public const NAMES = [\n";
    foreach ($names as $name => $_) {
        $t .= "        '$name',\n";
    }
    $t .= "    ];\n\n    public const KEYS = [\n";
    foreach ($names as $name => $k) {
        $t .= "        '$name' => $k,\n";
    }
    $t .= "    ];\n}\n";
    write('TagNames.php', $t);
    return count($members);
}

// ----- attributes -----

function attributes(string $src): int
{
    $names = read($src . 'Core/HtmlNames.cs');
    preg_match_all('/HtmlAttribute\.(\w+) => "([^"]+)"/', $names, $m, PREG_SET_ORDER);
    $special = [];
    foreach ($m as $x) {
        $special[$x[1]] = $x[2];
    }
    $b = header_for('HtmlAttribute.cs and HtmlNames.cs');
    $b .= "/**\n * Common HTML / SVG / XML attribute names, for HtmlNode::attr(), Query::attr() and the shortcuts. Any other\n";
    $b .= " * name works as a plain string.\n */\nfinal class Attr\n{\n";
    $seen = [];
    $constants = [];
    $members = enumMembers($src . 'HtmlAttribute.cs', 'HtmlAttribute');
    foreach ($members as $member) {
        $name = $special[$member] ?? strtolower($member);
        $c = constant_name($member);
        if ($c === 'CLASS') {
            $c = 'CLASS_'; // "class" cannot name a constant
        }
        if (isset($seen[$name]) || isset($constants[$c])) {
            throw new RuntimeException("duplicate attribute $name / $c");
        }
        $seen[$name] = $constants[$c] = true;
        $b .= "    public const $c = '$name';\n";
    }
    $b .= "\n    private function __construct()\n    {\n    }\n}\n";
    write('Attr.php', $b);
    return count($members);
}

// ----- entities -----

/** The concatenated string literals of `name = "..." + "...";`, escapes left as written. */
function constantText(string $text, string $name): string
{
    $start = strpos($text, "$name =");
    $end = strpos($text, ';', $start);
    preg_match_all('/"((?:[^"\\\\]|\\\\.)*)"/', substr($text, $start, $end - $start), $m);
    return implode('', $m[1]);
}

/** C# escapes (\uXXXX, \0) into a list of UTF-16 units. */
function units(string $s): array
{
    $out = [];
    for ($i = 0; $i < strlen($s); $i++) {
        $c = $s[$i];
        if ($c === '\\' && $i + 1 < strlen($s)) {
            $e = $s[$i + 1];
            if ($e === 'u') {
                $out[] = hexdec(substr($s, $i + 2, 4));
                $i += 5;
                continue;
            }
            if ($e === '0') {
                $out[] = 0;
                $i++;
                continue;
            }
            throw new RuntimeException("unexpected escape \\$e");
        }
        $out[] = ord($c);
    }
    return $out;
}

function entities(string $src): int
{
    $table = read($src . 'Core/HtmlEntities.Table.cs');
    $names = preg_split('/\s+/', trim(constantText($table, 'private const string Names')));
    $units = units(constantText($table, 'private const string Values'));
    if (count($units) !== 2 * count($names)) {
        throw new RuntimeException(count($names) . ' names, ' . count($units) . ' value units');
    }
    $maxName = 0;
    $maxLegacy = 0;
    $map = '';
    $legacy = '';
    foreach ($names as $i => $n) {
        $isLegacy = $n[0] === '+';
        $name = $isLegacy ? substr($n, 1) : $n;
        $maxName = max($maxName, strlen($name));
        $a = $units[2 * $i];
        $z = $units[2 * $i + 1];
        if ($z === 0) {
            $value = utf8($a);
        } elseif ($a >= 0xd800 && $a <= 0xdbff) {
            $value = utf8(0x10000 + (($a - 0xd800) << 10) + ($z - 0xdc00));
        } else {
            $value = utf8($a) . utf8($z);
        }
        $map .= "        '$name' => " . php_string($value) . ",\n";
        if ($isLegacy) {
            $maxLegacy = max($maxLegacy, strlen($name));
            $legacy .= "        '$name' => true,\n";
        }
    }
    $b = header_for('HtmlEntities.Table.cs');
    $b .= "/**\n * @internal The HTML5 named character references.\n */\nfinal class Entities\n{\n";
    $b .= "    public const MAX_NAME = $maxName;\n    public const MAX_LEGACY_NAME = $maxLegacy;\n\n";
    $b .= "    /** The names without \"&\" and \";\" and their values. */\n";
    $b .= "    public const MAP = [\n$map    ];\n\n";
    $b .= "    /** The legacy names, which are also recognized without \";\". */\n";
    $b .= "    public const LEGACY = [\n$legacy    ];\n}\n";
    write('Entities.php', $b);
    return count($names);
}

